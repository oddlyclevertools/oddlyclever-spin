"""Builds site/privacy.html and site/licences.html from launch/PRIVACY.md, THIRD_PARTY_NOTICES.md and LICENSE.
Run after any of those change:  python tools/site_pages.py   (needs: pip install markdown)"""
import html
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parent.parent
PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{title} · OddlyClever Spin</title>
<meta name="theme-color" content="#001233">
<link rel="icon" href="assets/favicon.ico" sizes="any">
<link rel="icon" href="assets/icon-rounded.svg" type="image/svg+xml">
<link rel="stylesheet" href="style.css">
</head>
<body>
<div class="wrap">
  <header class="top">
    <a href="./" aria-label="OddlyClever Spin home">
      <img class="wm-light" src="assets/wordmark-inline-light.svg" alt="OddlyClever Spin" width="224" height="34">
      <img class="wm-dark" src="assets/wordmark-inline-dark.svg" alt="OddlyClever Spin" width="224" height="34">
    </a>
    <nav><a href="./#download">Download</a><a href="./#faq">FAQ</a></nav>
  </header>
  <main class="doc">
<!-- Generated by tools/site_pages.py from {source}. Edit the source, not this file. -->
{body}
  </main>
  <footer>
    <nav><a href="privacy.html">Privacy</a><a href="licences.html">Licences</a><a href="https://github.com/oddlyclevertools/oddlyclever-spin">Source code</a></nav>
    Made by Oddly Clever Tools. Spin is not affiliated with YouTube, Google or any music service.
  </footer>
</div>
</body>
</html>
"""
SITE_NOTE = """
## This website

This site is a plain page on GitHub Pages. It has no cookies, no analytics and no web fonts. The download buttons ask GitHub's
public API for the newest release so they can link straight to the files. GitHub's own privacy statement covers that request.
"""


def md(text: str) -> str:
    return markdown.markdown(text, extensions=["tables"])


def write(name: str, title: str, source: str, body: str) -> None:
    out = ROOT / "site" / name
    out.write_text(PAGE.format(title=title, source=source, body=body), encoding="utf-8", newline="\n")
    print("wrote", out.relative_to(ROOT))


def main() -> None:
    privacy = (ROOT / "launch" / "PRIVACY.md").read_text(encoding="utf-8")
    write("privacy.html", "Privacy", "launch/PRIVACY.md", md(privacy + SITE_NOTE))
    notices = (ROOT / "THIRD_PARTY_NOTICES.md").read_text(encoding="utf-8").replace("# Third-party notices", "# Licences", 1)
    licence = html.escape((ROOT / "LICENSE").read_text(encoding="utf-8"))
    write("licences.html", "Licences", "THIRD_PARTY_NOTICES.md and LICENSE",
          md(notices) + "\n<h2>Spin's own licence (MIT)</h2>\n<pre>" + licence + "</pre>")


if __name__ == "__main__":
    main()
